"""
Paired bootstrap confidence intervals for CIRCO metrics.

WHAT THIS SCRIPT DOES
---------------------
Same as bootstrap_fashion.py but for CIRCO. Computes 95% CIs for:
  - mAP@5, @10, @25, @50
  - R@5, @10, @25, @50
  - R10_ref, mean/median_rank_ref, sim_ref, sim_gt, sim_delta
  - best_gt_rank statistics

PREREQUISITE
------------
Each checkpoint MUST have a circo_eval_v2.json next to it (generated by
evaluation/eval_circo_v2.py). This file contains the per-query data we need.

If the file is missing, this script errors with a clear message. We do NOT
auto-run the eval — that decision is left to the user.

BOOTSTRAP MATH
--------------
Same as Fashion bootstrap:
  - Resample query indices with replacement (B = 5000 times)
  - Compute aggregate metrics on each resample
  - 95% CI = [2.5th, 97.5th] percentile of the distribution

Key difference from Fashion: CIRCO has only ONE block of 220 queries (not
3 categories). So we bootstrap once per checkpoint, no category averaging.

PAIRED bootstrap (when --reference given):
  - Same indices applied to A and B each iteration
  - Compute (metric_A - metric_B) per iteration → distribution of differences
  - 95% CI of differences tells us if A really is better/worse than B

Usage:
    PYTHONPATH=/notebooks/experiment/codes python all_model_comparison/bootstrap_circo.py \
        --checkpoints A.pt B.pt C.pt \
        --reference baseline.pt \
        --n_bootstrap 5000
"""
import argparse
import json
from pathlib import Path

import numpy as np
from metrics.paths import metric_file_path, METRICS_ROOT

OUTPUT_JSON = METRICS_ROOT / 'bootstrap' / 'bootstrap_circo_results.json'


# ---------------------------------------------------------------------------
# CI summary helpers (identical to bootstrap_fashion.py — kept local for
# script independence)
# ---------------------------------------------------------------------------
def _ci_summary(samples, ci=95):
    """95% CI = [2.5th, 97.5th] percentile of bootstrap distribution."""
    lo_q = (100 - ci) / 2
    hi_q = 100 - lo_q
    return {
        'mean':   float(np.mean(samples)),
        'std':    float(np.std(samples)),
        'ci_lo':  float(np.percentile(samples, lo_q)),
        'ci_hi':  float(np.percentile(samples, hi_q)),
        'median': float(np.median(samples)),
    }


def _ci_diff_summary(diff_samples):
    """Same as _ci_summary plus 'sign flip rate' for differences."""
    s = _ci_summary(diff_samples)
    mean_sign = 1 if s['mean'] >= 0 else -1
    s['frac_sign_flip'] = float((diff_samples * mean_sign < 0).mean())
    return s


# ---------------------------------------------------------------------------
# Load circo_eval_v2.json next to the checkpoint.
# This is where per-query data lives. Error clearly if missing.
# ---------------------------------------------------------------------------
def _load_circo_v2(ckpt_path):
    """Load circo_eval_v2 JSON file from the metrics/ directory."""
    p = metric_file_path(ckpt_path, benchmark='circo')
    if not p.exists():
        raise FileNotFoundError(
            f'{p} does not exist.\n'
            f'Run: PYTHONPATH=/notebooks/experiment/codes '
            f'python evaluation/eval_circo_v2.py --checkpoint {ckpt_path}'
        )
    with open(p) as f:
        return json.load(f)


# ---------------------------------------------------------------------------
# Compute aggregate metrics from per-query data.
# 
# Inputs (all per-query, length n = 220 for CIRCO val):
#   rank_ref     : int per query   (rank of ref image when NOT excluded)
#   sim_ref      : float per query (sim score of query vs ref)
#   sim_gt_mean  : float|None per query (mean sim across GTs)
#   ap_at_k      : dict of '@K' -> list of per-query AP@K values
#   recall_at_k  : dict of '@K' -> list of per-query 0/1 hits at K
# 
# Math:
#   mAP@K          = mean over queries of AP@K(query)
#   R@K            = mean over queries of (was any GT in top-K of that query)
#   R10_ref        = fraction of queries where rank_ref <= 10
#   mean_rank_ref  = mean(rank_ref)
#   median_rank_ref= median(rank_ref)
#   sim_ref        = mean(sim_ref)
#   sim_gt         = mean(sim_gt_mean) over non-None values
#   sim_delta      = sim_ref - sim_gt  (positive = sticky)
# ---------------------------------------------------------------------------
def _metrics_from_per_query(pq):
    rank_ref = np.asarray(pq['rank_ref'])
    sim_ref  = np.asarray(pq['sim_ref'])
    # sim_gt_mean / best_gt_rank can be None when a query has no valid GTs in our gallery
    sim_gt   = np.array([x for x in pq['sim_gt_mean'] if x is not None])
    bgr      = np.array([x for x in pq['best_gt_rank'] if x is not None])

    return {
        'map5':  float(np.mean(pq['ap_at_k']['@5'])),
        'map10': float(np.mean(pq['ap_at_k']['@10'])),
        'map25': float(np.mean(pq['ap_at_k']['@25'])),
        'map50': float(np.mean(pq['ap_at_k']['@50'])),
        'r5':  float(np.mean(pq['recall_at_k']['@5'])),
        'r10': float(np.mean(pq['recall_at_k']['@10'])),
        'r25': float(np.mean(pq['recall_at_k']['@25'])),
        'r50': float(np.mean(pq['recall_at_k']['@50'])),
        'r10_ref':         float((rank_ref <= 10).mean()),
        'mean_rank_ref':   float(rank_ref.mean()),
        'median_rank_ref': float(np.median(rank_ref)),
        'sim_ref':         float(sim_ref.mean()),
        'sim_gt':          float(sim_gt.mean()) if len(sim_gt) else 0.0,
        'sim_delta':       float(sim_ref.mean() - sim_gt.mean()) if len(sim_gt) else 0.0,
        'best_gt_rank_mean':   float(bgr.mean())     if len(bgr) else 0.0,
        'best_gt_rank_median': float(np.median(bgr)) if len(bgr) else 0.0,
    }


# ---------------------------------------------------------------------------
# Pre-extract per-query arrays as numpy. Speeds up the bootstrap inner loop
# by ~10x (avoids list indexing overhead).
# ---------------------------------------------------------------------------
def _per_query_to_numpy(pq):
    """Convert per_query dict to numpy arrays. None values handled per metric."""
    return {
        'rank_ref'    : np.asarray(pq['rank_ref']),
        'sim_ref'     : np.asarray(pq['sim_ref']),
        # NaN for missing sim_gt_mean — easier to filter than None in vectorized code
        'sim_gt_mean' : np.array([x if x is not None else np.nan for x in pq['sim_gt_mean']]),
        # -1 sentinel for missing best_gt_rank (ranks are always >= 1, so -1 means "missing")
        'best_gt_rank': np.array([x if x is not None else -1 for x in pq['best_gt_rank']]),
        'ap5':  np.asarray(pq['ap_at_k']['@5']),
        'ap10': np.asarray(pq['ap_at_k']['@10']),
        'ap25': np.asarray(pq['ap_at_k']['@25']),
        'ap50': np.asarray(pq['ap_at_k']['@50']),
        'r5':   np.asarray(pq['recall_at_k']['@5']),
        'r10':  np.asarray(pq['recall_at_k']['@10']),
        'r25':  np.asarray(pq['recall_at_k']['@25']),
        'r50':  np.asarray(pq['recall_at_k']['@50']),
    }


# ---------------------------------------------------------------------------
# Bootstrap one checkpoint:
#   For b = 1..B:
#     idx_b = sample 220 indices with replacement
#     compute all metrics on resampled arrays
#     append to per-metric list
#   Return dict[metric] -> B-array
#
# Vectorized version avoids re-extracting None/NaN per iter — we pre-mask
# for missing values once outside the loop.
# ---------------------------------------------------------------------------
def _bootstrap(pq, n_bootstrap, rng):
    n = len(pq['rank_ref'])
    pq_np = _per_query_to_numpy(pq)

    # Get the list of metric names (use first call to _metrics_from_per_query as schema)
    metric_names = list(_metrics_from_per_query(pq).keys())
    samples = {k: [] for k in metric_names}

    for _ in range(n_bootstrap):
        # Sample 220 indices with replacement
        idx = rng.integers(0, n, n)

        # Slice resampled arrays
        rr   = pq_np['rank_ref'][idx]
        sr   = pq_np['sim_ref'][idx]
        sg   = pq_np['sim_gt_mean'][idx]
        bgr  = pq_np['best_gt_rank'][idx]
        # Filter sentinels in the resampled view
        bgr_valid = bgr[bgr >= 0]
        sg_valid  = sg[~np.isnan(sg)]

        # Append each metric
        samples['map5'].append(pq_np['ap5'][idx].mean())
        samples['map10'].append(pq_np['ap10'][idx].mean())
        samples['map25'].append(pq_np['ap25'][idx].mean())
        samples['map50'].append(pq_np['ap50'][idx].mean())
        samples['r5'].append(pq_np['r5'][idx].mean())
        samples['r10'].append(pq_np['r10'][idx].mean())
        samples['r25'].append(pq_np['r25'][idx].mean())
        samples['r50'].append(pq_np['r50'][idx].mean())
        samples['r10_ref'].append((rr <= 10).mean())
        samples['mean_rank_ref'].append(rr.mean())
        samples['median_rank_ref'].append(np.median(rr))
        samples['sim_ref'].append(sr.mean())
        sg_m = sg_valid.mean() if len(sg_valid) else 0.0
        samples['sim_gt'].append(sg_m)
        samples['sim_delta'].append(sr.mean() - sg_m)
        samples['best_gt_rank_mean'].append(bgr_valid.mean()     if len(bgr_valid) else 0.0)
        samples['best_gt_rank_median'].append(np.median(bgr_valid) if len(bgr_valid) else 0.0)

    return {k: np.array(v) for k, v in samples.items()}


# ---------------------------------------------------------------------------
# Paired bootstrap: same indices for both checkpoints each iteration.
# Returns dict[metric] -> B-array of (metric_A - metric_B) differences.
#
# We don't bother bootstrap-ing best_gt_rank differences (rare None handling
# would make the math messy without much gain). They appear as 0.0 in output.
# ---------------------------------------------------------------------------
def _paired_bootstrap(pqA, pqB, n_bootstrap, rng):
    n = len(pqA['rank_ref'])
    assert len(pqB['rank_ref']) == n, 'Query count mismatch'

    pA = _per_query_to_numpy(pqA)
    pB = _per_query_to_numpy(pqB)
    metric_names = list(_metrics_from_per_query(pqA).keys())
    diffs = {k: [] for k in metric_names}

    for _ in range(n_bootstrap):
        idx = rng.integers(0, n, n)

        # A side
        rrA = pA['rank_ref'][idx]
        srA = pA['sim_ref'][idx]
        sgA = pA['sim_gt_mean'][idx]
        sgA_v = sgA[~np.isnan(sgA)]
        # B side (same idx!)
        rrB = pB['rank_ref'][idx]
        srB = pB['sim_ref'][idx]
        sgB = pB['sim_gt_mean'][idx]
        sgB_v = sgB[~np.isnan(sgB)]

        # Compute per-iter A and B metrics, take difference, append
        diffs['map5'].append(pA['ap5'][idx].mean()   - pB['ap5'][idx].mean())
        diffs['map10'].append(pA['ap10'][idx].mean() - pB['ap10'][idx].mean())
        diffs['map25'].append(pA['ap25'][idx].mean() - pB['ap25'][idx].mean())
        diffs['map50'].append(pA['ap50'][idx].mean() - pB['ap50'][idx].mean())
        diffs['r5'].append(pA['r5'][idx].mean()   - pB['r5'][idx].mean())
        diffs['r10'].append(pA['r10'][idx].mean() - pB['r10'][idx].mean())
        diffs['r25'].append(pA['r25'][idx].mean() - pB['r25'][idx].mean())
        diffs['r50'].append(pA['r50'][idx].mean() - pB['r50'][idx].mean())
        diffs['r10_ref'].append((rrA <= 10).mean() - (rrB <= 10).mean())
        diffs['mean_rank_ref'].append(rrA.mean() - rrB.mean())
        diffs['median_rank_ref'].append(np.median(rrA) - np.median(rrB))
        diffs['sim_ref'].append(srA.mean() - srB.mean())
        sgA_m = sgA_v.mean() if len(sgA_v) else 0.0
        sgB_m = sgB_v.mean() if len(sgB_v) else 0.0
        diffs['sim_gt'].append(sgA_m - sgB_m)
        diffs['sim_delta'].append((srA.mean() - sgA_m) - (srB.mean() - sgB_m))
        # best_gt_rank diffs skipped — set to 0
        diffs['best_gt_rank_mean'].append(0.0)
        diffs['best_gt_rank_median'].append(0.0)

    return {k: np.array(v) for k, v in diffs.items()}


# ---------------------------------------------------------------------------
# Wrap one checkpoint: load, bootstrap, compute CIs.
# ---------------------------------------------------------------------------
def analyze_checkpoint(ckpt_path, n_bootstrap, rng):
    data = _load_circo_v2(ckpt_path)
    pq = data['per_query']
    point = _metrics_from_per_query(pq)
    samples = _bootstrap(pq, n_bootstrap, rng)
    cis = {m: _ci_summary(s) for m, s in samples.items()}
    for m in cis:
        cis[m]['point'] = point[m]
    return {'cis': cis, 'n_queries': len(pq['rank_ref'])}


def analyze_pair(ckpt_A, ckpt_B, n_bootstrap, rng):
    pA = _load_circo_v2(ckpt_A)['per_query']
    pB = _load_circo_v2(ckpt_B)['per_query']
    diffs = _paired_bootstrap(pA, pB, n_bootstrap, rng)
    return {m: _ci_diff_summary(s) for m, s in diffs.items()}


# ---------------------------------------------------------------------------
# CLI (same shape as bootstrap_fashion.py for consistency)
# ---------------------------------------------------------------------------
def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument('--checkpoints', nargs='+', required=True)
    p.add_argument('--reference', type=str, default=None)
    p.add_argument('--n_bootstrap', type=int, default=5000)
    p.add_argument('--seed', type=int, default=42)
    p.add_argument('--output_json', type=Path, default=OUTPUT_JSON)
    return p.parse_args()


def main():
    args = parse_args()
    rng = np.random.default_rng(args.seed)

    targets = list(args.checkpoints)
    if args.reference and args.reference not in targets:
        targets = [args.reference] + targets

    print(f'Analyzing {len(targets)} CIRCO checkpoints, {args.n_bootstrap} bootstrap iters')

    # Single-checkpoint CIs
    single_results = {}
    for ckpt in targets:
        print(f'\n  Single: {ckpt}')
        single_results[ckpt] = analyze_checkpoint(ckpt, args.n_bootstrap, rng)

    # Pairwise differences vs reference
    pair_results = {}
    if args.reference:
        for ckpt in args.checkpoints:
            if ckpt == args.reference:
                continue
            print(f'\n  Pair: {ckpt} vs reference')
            pair_results[f'{ckpt}__vs__{args.reference}'] = analyze_pair(
                ckpt, args.reference, args.n_bootstrap, rng
            )

    # Save
    output = {
        'meta': {
            'n_bootstrap': args.n_bootstrap,
            'seed': args.seed,
            'reference': args.reference,
            'checkpoints': args.checkpoints,
        },
        'single': single_results,
        'paired': pair_results,
    }
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output_json, 'w') as f:
        json.dump(output, f, indent=2)
    print(f'\nSaved to {args.output_json}')

    # Print key paired results to stdout. '*' = CI excludes zero → significant.
    print()
    print('=' * 100)
    print('PAIRED DIFFERENCES (vs reference), key metrics:')
    print('=' * 100)
    if pair_results:
        for pair_key, pair_res in pair_results.items():
            label = pair_key.split('__vs__')[0].split('/')[-2:]
            print(f'\n  {"/".join(label)}  vs  reference:')
            for m in ['map10', 'map25', 'r10', 'r10_ref', 'mean_rank_ref', 'sim_delta']:
                d = pair_res[m]
                sig = '*' if (d['ci_lo'] > 0 or d['ci_hi'] < 0) else ' '
                print(f'    {m:<20s} Δ = {d["mean"]:+.4f}  '
                      f'95% CI [{d["ci_lo"]:+.4f}, {d["ci_hi"]:+.4f}]  {sig}')


if __name__ == '__main__':
    main()
